#!/usr/bin/env python3
"""Regenerate tools/shipped_hashes.json: sha256 of every file the kit once shipped for a skill or command that
a later release removed. install.py compares a downstream copy against these hashes to decide whether a removed
skill is unmodified (safe to delete) or edited by the user (kept, with a warning).

  python tools/gen_shipped_hashes.py            rewrite tools/shipped_hashes.json from the git tags below

Hashes are taken over the file content with CRLF normalised to LF, because a Windows checkout with
core.autocrlf=true writes CRLF into the downstream copy. __pycache__ is never shipped, so never hashed.
Stdlib only; needs the tags in this clone (git fetch --tags).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
OUT = KIT / "tools" / "shipped_hashes.json"
TAGS = ("kit-v3", "v0.3.0", "v0.3.1", "v0.3.2", "v0.4.0")
REMOVED_SKILLS = ("crafting-prompts", "tracking-experiments", "grilling-designs", "managing-git")
REMOVED_COMMANDS = ("grill.md",)  # templates/commands/<name> -> .claude/commands/<name>


def git(*args: str) -> bytes | None:
    r = subprocess.run(["git", *args], cwd=KIT, capture_output=True)
    return r.stdout if r.returncode == 0 else None


def digest(data: bytes) -> str:
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def main() -> int:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    skills: dict[str, dict[str, set[str]]] = {n: {} for n in REMOVED_SKILLS}
    commands: dict[str, set[str]] = {n: set() for n in REMOVED_COMMANDS}
    seen = 0
    for tag in TAGS:
        if git("rev-parse", "--verify", "-q", tag) is None:
            print(f"WARN tag {tag} not found in this clone; skipped", file=sys.stderr)
            continue
        seen += 1
        for name in REMOVED_SKILLS:
            listing = git("ls-tree", "-r", "--name-only", tag, f"skills/{name}")
            for path in (listing or b"").decode("utf-8").splitlines():
                data = git("show", f"{tag}:{path}")
                if data is not None:
                    skills[name].setdefault(path.split("/", 2)[2], set()).add(digest(data))
        for name in REMOVED_COMMANDS:
            data = git("show", f"{tag}:templates/commands/{name}")
            if data is not None:
                commands[name].add(digest(data))
    if not seen:
        print("BLOCK: none of the release tags exist here; run `git fetch --tags`", file=sys.stderr)
        return 1
    doc = {
        "_comment": "generated by tools/gen_shipped_hashes.py; sha256 of LF-normalised file content per release tag",
        "tags": [t for t in TAGS],
        "skills": {n: {p: sorted(h) for p, h in sorted(files.items())} for n, files in skills.items()},
        "commands": {n: sorted(h) for n, h in commands.items()},
    }
    OUT.write_bytes((json.dumps(doc, indent=1, sort_keys=True) + chr(10)).encode("utf-8"))  # LF on every OS (.gitattributes eol=lf)
    print(f"OK: {OUT.relative_to(KIT)} from {seen} tag(s): "
          + ", ".join(f"{n}={len(f)} files" for n, f in skills.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
